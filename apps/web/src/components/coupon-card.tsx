import type { Coupon, CouponStatus } from '@im-coupon/contracts';

/**
 * 상태 값을 화면 문구로 옮기는 표. `'held'` 하나뿐인 것은 발급 이후 상태의 이름과 수가
 * 기획 노선 미결이어서다 (설계문서 7장) — 그래서 없는 상태의 문구를 미리 만들지 않는다.
 * 표로 두면 라이프사이클 에픽이 상태를 늘릴 때 이 표가 컴파일 오류로 문구를 요구한다.
 */
const STATUS_LABELS: Record<CouponStatus, string> = {
  held: '소유자 점유',
};

/**
 * 퍼센트 표기에서 곱셈 오차를 버리는 소수 자리.
 *
 * `비율 * 100` 은 IEEE 754 에서 정확하지 않다 — `0.07 * 100 === 7.000000000000001`,
 * `0.29 * 100 === 28.999999999999996`. 배정도의 유효자리가 십진 15자리 남짓이고
 * `0..1` 비율의 퍼센트는 정수부를 세 자리까지만 쓰므로, 오차는 늘 소수 12자리 밖에 있다.
 * 10자리에서 자르면 그 오차만 사라지고 비율이 실제로 가진 자리는 건드리지 않는다.
 */
const PERCENT_ERROR_CUTOFF = 10;

/**
 * 이중 기한을 적을 시간대의 오프셋(분)과 그 표시. 한국 표준시는 서머타임이 없어 고정
 * `+09:00` 이 연중 언제나 맞다 — 그래서 시간대 데이터베이스를 들출 이유가 없고, 이 상수와
 * 덧셈만으로 변환이 닫힌다. `Intl`·`toLocaleString`·`timeZone: 'Asia/Seoul'` 로 "고치지"
 * 마라. 결과가 로케일·ICU 데이터·실행 환경에 묶여 같은 커밋이 머신마다 다른 문자열을 낸다.
 */
const DISPLAY_OFFSET_MINUTES = 9 * 60;
const DISPLAY_ZONE_LABEL = 'KST';

export type CouponCardProps = Coupon;

/**
 * 쿠폰 한 건을 와이어프레임의 카드로 그린다 (설계문서 11장). props 만 받아 그리는 UI 전용
 * 컴포넌트다 — fetch·상태 로직을 갖지 않는다 (4장 결정 10).
 *
 * props 는 쿠폰 레코드 그대로다. 카드가 자기 모양을 따로 선언하지 않으므로 계약과 어긋날
 * 자리가 없다 — 발급 결과 카드(`CP-05-04`)가 응답 타입을 그대로 props 로 쓴 것과 같다.
 *
 * 이 카드가 거래조건 고지를 진다 — 배분 비율과 이중 기한을 본문과 같은 글자 크기로 두고
 * 축소 표기·각주 처리를 하지 않는다 (10장 이 브랜치). 그래서 세 고지 줄은 액면과 같은
 * `p` 이고, 이 저장소에 CSS 클래스 체계가 없는 것을 그대로 두어 축소 클래스를 만들지 않는다.
 *
 * 카드 한 장만 그린다. 같은 소유자의 쿠폰이 여러 건일 때 세로로 반복하는 배치는 화면
 * 조립(`CP-06-05`)의 몫이다.
 */
export function CouponCard({
  status,
  merchantName,
  faceValue,
  benefitSplit,
  heldUntil,
  expiresAt,
}: CouponCardProps) {
  return (
    /*
      목록 안에서 저마다 독립적으로 읽히는 항목이라 `article` 로 둔다. 접근 가능한 이름을
      가맹점명으로 주어, 카드가 세로로 반복될 때 화면 조립과 e2e 가 카드 하나를 집을 수 있다.
    */
    <article aria-label={merchantName}>
      {/* 컴포넌트 층의 헤딩은 `h3` 이하다 — 탭 셸 `h1` · 화면 조립 `h2` (설계문서 10장) */}
      <h3>{merchantName}</h3>
      <p>{STATUS_LABELS[status]}</p>
      {/*
        액면을 천 단위로 끊지 않는다. 같은 액면을 발급 결과 카드(`CP-05-04`)가 구분 기호
        없이 그리고 있어, 두 화면이 같은 값을 다른 모양으로 보이면 안 되는 것이 첫째 이유다.
        둘째는 구분 기호를 넣는 방법이 로케일 기본값(`Intl`·`toLocaleString`)에 기대게
        되는데, 그 기본값은 머신마다 달라 같은 커밋이 다른 문자열을 낸다는 것이다.
      */}
      <p>{`액면 ${faceValue}원 페이백`}</p>
      <hr />
      {/*
        고지 블록의 소제목을 헤딩으로 둔다 — 스크린 리더가 카드 안에서 고지로 바로 이동할 수
        있고, 카드 제목 `h3` 바로 아래 한 칸이라 `h4` 다. 브라우저 기본 스타일에서 `h4` 는
        본문과 같은 크기(`1em`)이므로 소제목이 고지를 작아 보이게 만들지 않는다. 그와 별개로
        고지 본문 세 줄은 헤딩이 아니라 `p` 로 두어, 헤딩 기본 스타일에 크기를 맡기지 않는다.
      */}
      <h4>거래조건</h4>
      {/*
        두 비율을 각각 옮긴다. 한쪽에서 다른 쪽을 빼 만들면(`100 - 소유자 몫`) 합은 늘 맞지만
        계약을 어긴 레코드가 왔을 때 화면이 레코드에 없는 수를 지어내 고지가 레코드와 달라진다.
        합이 맞는 것은 7장이 두 비율의 합을 `1` 로 제약한 결과이고 화면이 만들 성질이 아니다.
      */}
      <p>{`배분 비율 — 소유자 ${toPercentText(benefitSplit.ownerRatio)}% / 소비자 ${toPercentText(benefitSplit.consumerRatio)}%`}</p>
      <p>{`소유자 점유 기한 — ${toDisplayMinuteText(heldUntil)} 까지는 소유자만 사용`}</p>
      <p>{`유효 소비 기한 — ${toDisplayMinuteText(expiresAt)} 에 만료`}</p>
    </article>
  );
}

/**
 * `0..1` 의 비율(설계문서 7장)을 퍼센트 수 표기로 옮긴다 — `0.2` 는 `20`, `0.125` 는 `12.5`.
 *
 * 자리를 줄이는 반올림은 하지 않는다. 7장이 두 비율의 합을 `1` 로 제약하므로 화면의 두
 * 퍼센트 합도 100 이어야 하는데, 자리를 줄이면 합이 어긋난다 — `0.125`/`0.875` 를 정수로
 * 반올림하면 `13%`/`88%` 가 되어 101% 가 되고, 합이 맞지 않는 수를 보이는 거래조건 고지는
 * 고지 자체가 의심받는다. 그래서 버리는 것은 곱셈 오차뿐이다 (`PERCENT_ERROR_CUTOFF`).
 */
function toPercentText(ratio: number): string {
  return String(Number((ratio * 100).toFixed(PERCENT_ERROR_CUTOFF)));
}

/**
 * ISO 8601 UTC 시각(설계문서 7장)을 `YYYY-MM-DD HH:mm KST` 절대 시각으로 옮긴다
 * (설계문서 11장의 표시 규칙).
 *
 * 절대 시각인 이유 — 7장이 두 기한을 일수 파라미터가 아니라 절대 시각으로 저장한 것은
 * 파라미터 변경의 소급 영향을 끊기 위해서다. 고지 표기도 절대 시각이어야 그 의도가 화면까지
 * 선다. 상대 표현("3일 뒤")은 같은 레코드를 읽는 시점마다 다른 문장을 만들어, 고지 내용이
 * 레코드가 아니라 읽은 시점에 매달린다.
 *
 * UTC 원문을 그대로 적지 않는 이유 — 고지의 목적은 읽히는 것이다. 시간대 표시 없는 UTC 는
 * 읽는 사람에게 아홉 시간 암산을 넘기고, 암산하지 않은 사람은 `05:00` 을 그 지역 시각으로
 * 잘못 읽는다. 배분 비율을 본문 크기로 노출하라고 못박은 문서가 기한만 변환 숙제로 남기는
 * 것은 앞뒤가 맞지 않는다. 그래서 시민이 읽는 시각으로 옮기고 시간대를 표기에 밝힌다.
 *
 * 그러면서도 결정론은 지킨다 — 변환이 고정 오프셋 덧셈과 `getUTC*` 뿐이라 결과가 실행
 * 머신의 시간대·로케일의 함수가 아니고, 테스트도 환경을 갈아끼우지 않고 값을 그대로
 * 단언한다 (12장 — 단위 테스트는 환경을 갈아끼우지 않는다). 자리 채움까지 직접 하는 것도
 * 같은 이유다.
 *
 * 이 변환은 이 카드에만 둔다. 발급 결과 카드(`CP-05-04`)는 시연·관리 시점 화면이라 저장
 * 원문인 ISO 를 그대로 보이는 쪽이 정확하다 (11장).
 */
function toDisplayMinuteText(iso: string): string {
  /*
    오프셋을 시각에 더하는 대신 순간(epoch)에 더하고 `getUTC*` 로 읽는다. 그래야 날짜·월·연
    자리가 함께 넘어간다 — 시·분만 더하면 `2026-09-31` 같은 없는 날짜가 만들어진다.
  */
  const at = new Date(new Date(iso).getTime() + DISPLAY_OFFSET_MINUTES * 60 * 1000);
  const date = `${at.getUTCFullYear()}-${padTwo(at.getUTCMonth() + 1)}-${padTwo(at.getUTCDate())}`;
  const time = `${padTwo(at.getUTCHours())}:${padTwo(at.getUTCMinutes())}`;

  return `${date} ${time} ${DISPLAY_ZONE_LABEL}`;
}

/** 월·일·시·분을 두 자리로 채운다. 연도는 이미 네 자리라 이 함수를 지나지 않는다 */
function padTwo(value: number): string {
  return String(value).padStart(2, '0');
}
