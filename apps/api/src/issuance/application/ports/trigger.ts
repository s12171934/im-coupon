import type { SignalWeights, TriggerType } from '@im-coupon/contracts';

/**
 * 발급 명령 — 트리거가 만들어 발급 유스케이스에 넘기는 것.
 *
 * 트리거마다 계기가 다르지만 넘기는 것은 이 한 형태다. 계기의 차이를 여기서 지우므로
 * 발급 유스케이스는 어느 트리거가 불렀는지와 무관하게 같은 절차를 밟는다.
 */
export interface IssueCommand<T extends TriggerType = TriggerType> {
  /** 이 발급을 일으킨 트리거의 유형. 그대로 쿠폰 레코드의 `trigger` 가 된다 */
  trigger: T;
  /**
   * 요청이 지정한 발급 가중치 부분 덮어쓰기. 생략하면 발급 파라미터 기본값으로 발급한다.
   *
   * 값이 `undefined` 인 키를 트리거가 걷어내지 않고 그대로 싣는다 — `Partial` 의
   * "지정하지 않음"을 기본값으로 옮기는 자리는 병합을 맡은 엔진 한 곳이며, 걷어내는
   * 자리를 둘로 늘리면 두 자리의 판정이 어긋날 때 조용히 다른 결과가 난다. 알려진 키의
   * `null` 도 마찬가지로 손대지 않는다 — 엔진이 "숫자가 아님"으로 거부해야 하는 값이다.
   */
  weights?: Partial<SignalWeights>;
}

/**
 * 발급 트리거 — 서로 다른 계기를 같은 발급 명령으로 옮기는 자리.
 *
 * 소비 도달·참여 리워드·가맹점 요청은 각자 다른 계기에서 발급을 일으키지만, 트리거가
 * 하는 일은 발급 명령을 만들어 발급 유스케이스에 넘기는 것으로 같다. 신호 확장 구조와
 * 대칭으로 인터페이스에 자리만 남겨, 이후 에픽이 같은 틀로 트리거를 더한다.
 *
 * `Occasion` 이 그 계기다 — 시연 트리거는 발급 요청 본문이고, 이후 트리거는 소비 이벤트나
 * 가맹점의 요청처럼 각자의 것을 받는다. 타입 매개변수로 두어 계기의 모양이 인터페이스에
 * 고정되지 않게 한다.
 *
 * `T` 는 그 트리거의 유형이다. **구현은 자기 유형을 이 매개변수로 좁혀 선언한다** —
 * `IssueTrigger<계기, '유형'>`. 좁히면 `type` 과 명령의 `trigger` 가 같은 `T` 를 써서
 * 타입이 둘을 묶으므로, 어긋난 값을 넣은 트리거는 컴파일되지 않는다.
 *
 * 기본값을 두지 않은 것은 그 묶음이 생략만으로 풀리지 않게 하려는 것이다 — 기본값이 있으면
 * 매개변수를 빠뜨린 구현이 `TriggerType` 전체로 넓어진 채 통과해, 묶음을 사람이 지키는
 * 규칙으로 되돌린다. 유형을 가리지 않고 트리거를 담아야 하는 쪽은 `IssueTrigger<계기,
 * TriggerType>` 으로 넓힘을 드러내 쓴다.
 */
export interface IssueTrigger<Occasion, T extends TriggerType> {
  /**
   * 이 트리거가 만드는 명령의 `trigger` 값에 대한 트리거 자신의 선언.
   *
   * 쿠폰 레코드로 가는 값은 명령의 `trigger` 이고 이 필드는 그것에 대한 선언이다. 둘이
   * 어느 쪽을 기준으로 삼을지 정할 필요가 없도록 `T` 로 묶어, 어긋날 수 있는 자리를
   * 애초에 만들지 않았다 — 신호의 `key` 와 엔진의 신호 맵 키가 어긋날 수 있어 "맵 키를
   * 기준으로 한다"는 규칙이 필요했던 것과 다른 처리다. 여기서는 규칙 대신 타입이 든다.
   */
  type: T;
  toCommand(occasion: Occasion): IssueCommand<T>;
}
